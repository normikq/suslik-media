#pragma once
#include <QPoint>
#include <QtGlobal>
class QWindow;

/// Собственный заголовок окна: системная полоса заголовка убрана, её место занимает заголовок из QML (TitleBar.qml).
/// Windows: окно остаётся обычным (WS_OVERLAPPEDWINDOW) — тень, прилипание к краям (Win+стрелки, перетаскивание к краю),
/// анимации сворачивания и изменение размера за боковые и нижний края работают средствами системы. Верхняя полоса
/// (рамка и заголовок) становится частью окна через «свои поля» Qt (customMargins): Qt сам пересчитывает их в
/// WM_NCCALCSIZE и при смене DPI, его геометрия окна совпадает с настоящей. Вне Windows — окно без рамки.
namespace suslik::app::TitleBar {
/// Тёмная тема окна для системы (рамка Windows 11 без цветной линии, тёмные системные меню).
void style(QWindow *w);
/// Убрать (on) или вернуть системную полосу заголовка. Перед окном без рамки (полный экран, мини-плеер) — вернуть.
void hideCaption(QWindow *w, bool on);
/// Толщина верхней полосы, за которую тянут размер окна (физические пиксели); 0 — вне Windows.
int resizeBorder(QWindow *w);
/// Развёрнутое окно Windows выходит за экран на толщину рамки: на столько опускается всё содержимое (логические пиксели).
qreal maximizedInset(QWindow *w);
/// Системное меню окна (Восстановить, Переместить, Размер, Свернуть, Развернуть, Закрыть) в точке экрана (логической).
void systemMenu(QWindow *w, const QPoint &globalPos);
}
